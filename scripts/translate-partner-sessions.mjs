async function run() {
  await mongoose.connect(uri);
  const col = mongoose.connection.db.collection("partnersessions");
  const sessions = await col.find({}).toArray();

  for (const s of sessions) {
    const idStr = s._id.toString();
    const mapEntry = TRANSLATIONS_MAP[idStr];
    if (!mapEntry) continue;

    const arTitle = mapEntry.title || s.title;
    const arPartnerName = mapEntry.partnerName || s.partnerName;
    const arDescription = mapEntry.description || s.description;

    let updatedVariants = s.variants;
    if (Array.isArray(s.variants) && s.variants.length > 0 && mapEntry.variantsAr) {
      updatedVariants = s.variants.map((v) => {
        const vMap = mapEntry.variantsAr[v.title];
        if (!vMap) return v;
        return {
          ...v,
          translations: {
            ...(v.translations || {}),
            ar: {
              title: vMap.title,
              description: vMap.description,
            },
          },
        };
      });
    }

    const updateDoc = {
      translations: {
        ...(s.translations || {}),
        ar: {
          title: arTitle,
          partnerName: arPartnerName,
          description: arDescription,
        },
      },
    };
    if (updatedVariants) {
      updateDoc.variants = updatedVariants;
    }

    await col.updateOne({ _id: s._id }, { $set: updateDoc });
    console.log(`Updated session ${idStr}: ${arPartnerName} - ${arTitle}`);
  }

  await mongoose.disconnect();
  console.log("All partner sessions translated successfully!");
}

run();
